import hashlib
import json

import pandas as pd
import pytest

from northstar_tabular.pipeline import (
    PipelineError,
    load_dataset,
    predict,
    train_and_evaluate,
    validate_inference_payload,
)


def write_fixture(tmp_path, *, group_column="session_id", reviewed=True):
    rows = []
    for session in range(60):
        for frame in range(4):
            value = (session % 2) * 10 + frame / 10
            rows.append(
                {
                    "session_id": f"session-{session}",
                    "signal": value,
                    "condition": "script-a" if session % 2 else "script-b",
                    "annotation": "positive" if session % 2 else "negative",
                }
            )
    data = tmp_path / "fixture.csv"
    pd.DataFrame(rows).to_csv(data, index=False)
    manifest = {
        "dataset_name": "generated-test-fixture",
        "source_url": "https://example.invalid/generated-fixture",
        "version": "test-only",
        "license": "CC0-1.0 test fixture",
        "license_url": "https://creativecommons.org/publicdomain/zero/1.0/",
        "license_evidence": "Generated fixture notice in this unit-test file",
        "license_reviewed": True,
        "attribution": "Generated by unit test; not external dataset data",
        "retrieved_at": "2026-01-01",
        "file_path": data.name,
        "sha256": hashlib.sha256(data.read_bytes()).hexdigest(),
        "target_column": "annotation",
        "positive_label": "positive",
        "group_column": group_column,
        "label_semantics": "Generated class for pipeline unit tests only",
        "limitations": ["Synthetic fixture; not representative of student behavior."],
        "research_only": True,
        "provenance_reviewed": reviewed,
    }
    manifest_path = tmp_path / "manifest.json"
    manifest_path.write_text(json.dumps(manifest), encoding="utf-8")
    return manifest_path


def test_provenance_gate_blocks_training_on_unreviewed_data(tmp_path):
    path = write_fixture(tmp_path, reviewed=False)

    with pytest.raises(PipelineError, match="provenance has not been reviewed"):
        load_dataset(path)


def test_group_holdout_training_artifact_and_strict_inference(tmp_path):
    manifest_path = write_fixture(tmp_path)
    dataset = load_dataset(manifest_path)
    output = tmp_path / "artifacts"

    report = train_and_evaluate(dataset, output, seed=13)
    artifact = __import__("joblib").load(output / "model.joblib")
    row = {"signal": 10.2, "condition": "unseen-category"}
    validated = validate_inference_payload(artifact["contract"], row)
    prediction = predict(output / "model.joblib", row)

    assert report["run"]["split_type"] == "group_holdout"
    assert report["run"]["train_group_count"] + report["run"]["test_group_count"] == 60
    assert report["run"]["test_rows"] == 48
    assert list(validated.columns) == ["signal", "condition"]
    assert 0 <= prediction["positive_label_probability"] <= 1
    assert prediction["model_use"] == "research_only_not_for_student_decisions"
    assert (output / "evaluation.json").is_file()
    assert (output / "MODEL_CARD.md").is_file()
    with pytest.raises(PipelineError, match="Feature mismatch"):
        validate_inference_payload(artifact["contract"], {**row, "unexpected": 1})


def test_unseen_group_split_label_in_test_is_rejected(tmp_path):
    path = write_fixture(tmp_path)
    frame = pd.read_csv(tmp_path / "fixture.csv")
    frame["annotation"] = "negative"
    frame.loc[frame["session_id"] == "session-59", "annotation"] = "positive"
    data = tmp_path / "fixture.csv"
    frame.to_csv(data, index=False)
    manifest = json.loads(path.read_text())
    manifest["sha256"] = hashlib.sha256(data.read_bytes()).hexdigest()
    path.write_text(json.dumps(manifest))
    dataset = load_dataset(path)

    with pytest.raises(PipelineError, match="Both classes must occur"):
        train_and_evaluate(dataset, tmp_path / "out", seed=42, test_size=0.1)
